let current = 'en';

export function pickLanguage(saved, browser) {
  if (LANGS.includes(saved)) return saved;
  const short = String(browser || 'en').slice(0, 2);
  return LANGS.includes(short) ? short : 'en';
}

export const getLang = () => current;
export const setLang = (lang) => { current = lang; };
export const t = (id) => STRINGS[current][id] ?? STRINGS.en[id] ?? '';
